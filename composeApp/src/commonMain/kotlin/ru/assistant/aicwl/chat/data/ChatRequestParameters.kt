package ru.assistant.aicwl.chat.data

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Параметры запроса к API чата Z.AI.
 *
 * Этот класс инкапсулирует все параметры, которые управляют поведением генерации текста AI-моделями.
 * Параметры позволяют настраивать баланс между креативностью и детерминизмом ответов,
 * controlar длину генерируемого текста и включать специальные режимы работы модели.
 *
 * Все параметры имеют значения по умолчанию, рекомендованные документацией Z.AI.
 *
 * @see <a href="https://docs.z.ai/guides/overview/concept-param">Документация Z.AI по параметрам</a>
 */
@Serializable
data class ChatRequestParameters(
    /**
     * Определяет, использовать ли семплирование для увеличения разнообразия ответов.
     *
     * **Пояснение:**
     * - `true`: Используется случайное семплирование на основе вероятности токенов.
     *   Это увеличивает разнообразие и креативность ответов, так как модель может выбрать
     *   не только наиболее вероятный токен, но и менее вероятные варианты.
     * - `false`: Используется жадная стратегия (greedy decoding), когда всегда выбирается
     *   токен с наивысшей вероятностью. Это делает ответы более предсказуемыми и детерминированными.
     *
     * **Рекомендации:**
     * - Используйте `true` для творческих задач (генерация идей, рассказов, вариантов решения)
     * - Используйте `false` для задач, требующих точности и стабильности (код, техническая документация)
     *
     * **По умолчанию:** `true`
     */
    @SerialName("do_sample")
    val doSample: Boolean = true,

    /**
     * Контролирует случайность выхода при семплировании.
     *
     * **Пояснение:**
     * Параметр temperature влияет на распределение вероятностей токенов:
     * - **Низкие значения (0.1 - 0.3):** Модель становится более консервативной,
     *   выбирая только наиболее вероятные токены. Ответы становятся более детерминированными,
     *   сосредоточенными и безопасными.
     * - **Средние значения (0.4 - 0.7):** Баланс между разнообразием и релевантностью.
     *   Подходит для большинства задач.
     * - **Высокие значения (0.8 - 1.0):** Модель становится более креативной и непредсказуемой.
     *   Ответы более разнообразные, но могут быть менее связными.
     * - **Очень высокие значения (> 1.0):** Экстремально случайные ответы, часто не связанные с контекстом.
     *
     * **Взаимодействие с другими параметрами:**
     * - Рекомендуется использовать только один из параметров: `temperature` ИЛИ `top_p`
     * - При использовании вместе с `top_p`, эффект temperature проявляется сильнее
     *
     * **Примеры использования:**
     * - `0.2` - техническая документация, SQL-запросы, фактическая информация
     * - `0.5` - деловая переписка, аналитика, структурированные ответы
     * - `0.8` - креативный текст, мозговой штурм, вариативные решения
     *
     * **По умолчанию:** Зависит от модели (обычно 0.7 - 0.9)
     */
    val temperature: Float? = null,

    /**
     * Контролирует разнообразие через nucleus sampling (также известный как top-p sampling).
     *
     * **Пояснение:**
     * Параметр определяет минимальную кумулятивную вероятность набора токенов,
     * из которых модель выбирает следующий токен:
     * - **Низкие значения (0.1 - 0.3):** Модель выбирает из очень узкого круга
     *   наиболее вероятных токенов. Это делает ответы очень предсказуемыми и консервативными.
     * - **Средние значения (0.5 - 0.8):** Баланс между разнообразием и качеством.
     * - **Высокие значения (0.9 - 0.95):** Модель рассматривает широкий спектр токенов,
     *   что увеличивает разнообразие ответов.
     * - `1.0`: Полное отключение nucleus sampling (рассматриваются все токены)
     *
     **Принцип работы:**
     * Модель сортирует все возможные токены по вероятности и берет минимальный набор
     * токенов в "хвосте" распределения, сумма вероятностей которых достигает значения top_p.
     *
     * **Взаимодействие с другими параметрами:**
     * - Рекомендуется использовать только один из параметров: `top_p` ИЛИ `temperature`
     * - При `top_p = 0.1` модель почти всегда будет предсказуемой
     * - При `top_p = 0.9` модель будет более творческой
     *
     * **Рекомендуемые значения:**
     * - `0.1 - 0.3` - для технических задач, кода, фактов
     * - `0.5 - 0.7` - для деловой переписки, инструкций
     * - `0.8 - 0.95` - для креативных задач, мозгового штурма
     *
     * **По умолчанию:** Зависит от модели (обычно 0.8 - 0.9)
     */
    @SerialName("top_p")
    val topP: Float? = null,

    /**
     * Ограничивает максимальное количество токенов в генерируемом ответе.
     *
     * **Пояснение:**
     * Определяет верхнюю границу длины ответа модели в токенах. Один токен примерно
     * соответствует 4 символам английского текста или 2-3 символам русского текста.
     *
     * **Влияние на ответ:**
     * - Если установить слишком низкое значение, ответ может быть обрезан посреди предложения
     * - Высокие значения позволяют генерировать более подробные и развёрнутые ответы
     * - Фактическая длина ответа может быть меньше, если модель завершает мысль раньше
     *
     * **Ограничения по моделям:**
     * - **glm-4.7:** default=65536, max=131072 токенов
     * - **glm-4.6:** default=65536, max=131072 токенов
     * - **glm-4.5-air:** default=65536, max=98304 токенов
     *
     * **Рекомендации:**
     * - Короткие ответы (128-512): быстрые вопросы, факты, определения
     * - Средние ответы (1024-2048): объяснения, инструкции, решения
     * - Длинные ответы (4096+): подробные руководства, анализ, генерация кода
     * - Рекомендуется устанавливать не менее 1024 для полноценных ответов
     *
     * **Примечание:** Токены ввода (prompt) и токены вывода (completion) суммируются
     * в общем контекстном окне модели.
     *
     * **По умолчанию:** Зависит от модели (обычно 65536)
     */
    @SerialName("max_tokens")
    val maxTokens: Int? = null,

    /**
     * Определяет режим передачи ответа от API.
     *
     * **Пояснение:**
     * - `false`: API возвращает полный ответ целиком после его полной генерации.
     *   Это проще в обработке, но пользователь ждёт дольше первого отображения текста.
     * - `true`: API возвращает ответ в потоковом режиме через Server-Sent Events (SSE).
     *   Токены поступают постепенно по мере генерации, что позволяет отображать ответ
     *   в реальном времени (эффект "печатания").
     *
     * **Преимущества потокового режима (stream=true):**
     * - Мгновенная обратная связь: пользователь видит начало ответа сразу
     * - Лучше user experience для длинных ответов
     * - Возможность прервать генерацию по желанию пользователя
     * - Восприятие меньшей задержки (time-to-first-token)
     *
     * **Недостатки потокового режима:**
     * - Более сложная реализация клиента
     * - Необходимость обработки частичных ответов
     * - Требует управления состоянием потока
     *
     * **Рекомендации:**
     * - Используйте `true` для интерактивных чат-интерфейсов (лучшая UX)
     * - Используйте `false` для пакетной обработки, API-интеграций, когда ответ
     *   обрабатывается целиком
     *
     * **По умолчанию:** `false`
     */
    val stream: Boolean = false,

    /**
     * Параметры включения режима "цепочки рассуждений" (Chain-of-Thought reasoning).
     *
     * **Пояснение:**
     * Режим мышления (thinking mode) позволяет модели внутренне "рассуждать" перед тем,
     * как дать финальный ответ. Это улучшает качество решений на сложных задачах,
     * требующих многошаговой логики, анализа, планирования.
     *
     * **Как это работает:**
     * 1. Модель генерирует внутренний монолог ("thinking content"), где анализирует задачу
     * 2. На основе этого анализа формируется финальный ответ для пользователя
     * 3. При необходимости можно получить оба текста (рассуждение + ответ)
     *
     * **Поддерживаемые модели:**
     * - GLM-4.5 и выше поддерживают режим мышления
     * - Для более старых моделей параметр игнорируется
     *
     * **Когда использовать:**
     * ✅ **Рекомендуется включать для:**
     * - Математических задач и вычислений
     * - Логических головоломок
     * - Анализа сложных сценариев
     * - Многошагового планирования
     * - Отладки кода и поиска ошибок
     * - Задач на причинно-следственные связи
     *
     * ❌ **Не рекомендуется для:**
     * - Простых вопросов фактического характера
     * - Генерации текста по шаблону
     * - Быстрых ответов, когда скорость важнее качества
     *
     * **Типы режима:**
     * - `enabled`: Режим мышления активирован, модель рассуждает перед ответом
     * - `disabled`: Стандартный режим без явного рассуждения
     *
     * **Примечание:** При `enabled` ответ может занимать больше времени,
     * но качество выше для сложных задач.
     *
     * **По умолчанию:** `ThinkingConfig(type = "enabled")`
     */
    val thinking: ThinkingConfig = ThinkingConfig(),

    /**
     * Максимальное количество попытокsemantic sampling (семантического семплирования).
     *
     * **Пояснение:**
     * Дополнительный параметр для улучшения качества ответов при работе со сложными
     * или неоднозначными запросами. Увеличивает количество внутренних итераций
     * при выборе оптимального ответа.
     *
     * **Влияние:**
     * - Более высокие значения могут улучшить качество ответов на сложные задачи
     * - Увеличивает время генерации
     * - Рекомендуемые значения: 1-3
     *
     * **По умолчанию:** 1
     */
    val n: Int = 1

    /**
     * Дополнительные параметры, которые могут быть добавлены в будущем.
     *
     * Используется для расширения функциональности без изменения основной структуры класса.
     */
) {
    /**
     * Валидирует параметры на соответствие ограничениям API.
     *
     * @throws IllegalArgumentException если параметры выходят за допустимые пределы
     */
    fun validate() {
        if (temperature != null && (temperature < 0f || temperature > 2f)) {
            throw IllegalArgumentException("Temperature должен быть в диапазоне от 0 до 2, получено: $temperature")
        }

        if (topP != null && (topP < 0f || topP > 1f)) {
            throw IllegalArgumentException("TopP должен быть в диапазоне от 0 до 1, получено: $topP")
        }

        if (maxTokens != null && maxTokens < 1) {
            throw IllegalArgumentException("MaxTokens должен быть положительным числом, получено: $maxTokens")
        }

        if (n < 1) {
            throw IllegalArgumentException("N (количество попыток) должен быть >= 1, получено: $n")
        }
    }

    /**
     * Создаёт копию параметров с изменёнными значениями.
     *
     * Удобен для создания вариаций параметров на основе базовой конфигурации.
     */
    fun copyWithChanges(
        doSample: Boolean = this.doSample,
        temperature: Float? = this.temperature,
        topP: Float? = this.topP,
        maxTokens: Int? = this.maxTokens,
        stream: Boolean = this.stream,
        thinking: ThinkingConfig = this.thinking,
        n: Int = this.n
    ): ChatRequestParameters {
        return ChatRequestParameters(
            doSample = doSample,
            temperature = temperature,
            topP = topP,
            maxTokens = maxTokens,
            stream = stream,
            thinking = thinking,
            n = n
        )
    }

    companion object {
        /**
         * Создаёт предустановку параметров для экстремально креативных задач.
         *
         * Характеристики:
         * - Максимальная креативность и разнообразие ответов
         * - Экстремально высокая температура (1.9) с nucleus sampling (0.9)
         * - Подходит для генерации неожиданных идей, альтернативных сценариев, фантастики
         * - Ответы могут быть очень непредсказуемыми и нестандартными
         * - Включён режим мышления для улучшения качества рассуждений
         */
        fun fantasyPlus() = ChatRequestParameters(
            doSample = true,
            temperature = 1.9f,
            topP = 0.9f,
            maxTokens = null,
            stream = false,
            thinking = ThinkingConfig.enabled()
        )

        /**
         * Создаёт предустановку параметров для высококреативных задач.
         *
         * Характеристики:
         * - Очень высокая креативность и разнообразие ответов
         * - Высокая температура (1.2) для максимального разнообразия
         * - Подходит для творческого письма, Brainstorming, генерации историй
         * - Ответы менее предсказуемые, но более креативные
         * - Включён режим мышления для улучшения качества рассуждений
         */
        fun fantasy() = ChatRequestParameters(
            doSample = true,
            temperature = 1.2f,
            topP = null,
            maxTokens = null,
            stream = false,
            thinking = ThinkingConfig.enabled()
        )

        /**
         * Создаёт предустановку параметров для творческих задач.
         *
         * Характеристики:
         * - Высокая креативность и разнообразие ответов
         * - Подходит для генерации идей, историй, вариантов решений
         * - Меньше детерминизма, больше случайности
         */
        fun creative() = ChatRequestParameters(
            doSample = true,
            temperature = 0.8f,
            topP = null,
            maxTokens = null,
            stream = false,
            thinking = ThinkingConfig.enabled()
        )

        /**
         * Создаёт предустановку параметров для технических задач.
         *
         * Характеристики:
         * - Высокая детерминированность и точность
         * - Подходит для кода, технической документации, фактов
         * - Минимум случайности, предсказуемые результаты
         */
        fun technical() = ChatRequestParameters(
            doSample = false,
            temperature = 0.2f,
            topP = null,
            maxTokens = null,
            stream = false,
            thinking = ThinkingConfig.enabled()
        )

        /**
         * Создаёт предустановку параметров для сбалансированных задач.
         *
         * Характеристики:
         * - Баланс между креативностью и точностью
         * - Подходит для большинства повседневных задач
         * - Разнообразные, но связные ответы
         */
        fun balanced() = ChatRequestParameters(
            doSample = false,
            temperature = 0.5f,
            topP = null,
            maxTokens = null,
            stream = false,
            thinking = ThinkingConfig.enabled()
        )

        /**
         * Создаёт предустановку параметров для быстрых ответов.
         *
         * Характеристики:
         * - Максимальная скорость генерации
         * - Короткие, лаконичные ответы
         * - Подходит для простых вопросов и фактов
         */
        fun fast() = ChatRequestParameters(
            doSample = false,
            temperature = 0.0f,
            topP = null,
            maxTokens = null,
            stream = false,
            thinking = ThinkingConfig.disabled()
        )
    }
}

/**
 * Конфигурация режима мышления (Chain-of-Thought reasoning).
 *
 * @see ChatRequestParameters.thinking
 */
@Serializable
data class ThinkingConfig(
    /**
     * Тип режима мышления.
     *
     * - `enabled`: Включает режим цепочки рассуждений
     * - `disabled`: Отключает режим цепочки рассуждений
     */
    val type: String = "enabled"
) {
    companion object {
        /**
         * Создаёт конфигурацию с включённым режимом мышления.
         */
        fun enabled() = ThinkingConfig(type = "enabled")

        /**
         * Создаёт конфигурацию с отключённым режимом мышления.
         */
        fun disabled() = ThinkingConfig(type = "disabled")
    }
}
